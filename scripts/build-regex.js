// Reproducible, locally served engine artifact; no WASM, CDN or npm resolution at runtime.
import {build} from 'esbuild';
import {readFile,mkdir} from 'node:fs/promises';
const pkg=JSON.parse(await readFile(new URL('../node_modules/re2js/package.json',import.meta.url),'utf8'));
if(pkg.version!=='2.8.6')throw Error('The regex safety review requires RE2JS 2.8.6');
const license=await readFile(new URL('../node_modules/re2js/LICENSE',import.meta.url),'utf8');
await mkdir(new URL('../packages/wydgine/src/engine/sewn/vendor/',import.meta.url),{recursive:true});
await build({stdin:{contents:"export {RE2JS} from 're2js';",resolveDir:process.cwd()},outfile:'packages/wydgine/src/engine/sewn/vendor/re2js.js',bundle:true,platform:'browser',format:'esm',target:'es2022',minify:true,legalComments:'none',banner:{js:`/*! RE2JS 2.8.6; generated by scripts/build-regex.js.\n${license}*/`}});
